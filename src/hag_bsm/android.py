"""Android signing operations built on keytool and apksigner.

Nothing here implements cryptography itself: keys are generated by keytool, signatures are
verified by apksigner, and certificates are parsed with the `cryptography` package.
"""

import hashlib
import re
import zipfile
from dataclasses import dataclass, field
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import dsa, ec, ed25519, rsa
from cryptography.hazmat.primitives.serialization import Encoding

from .tools import AndroidTools, ToolMissingError, run

# keytool output is localised; force English so it can be parsed reliably.
_KT_LOCALE = ["-J-Duser.language=en", "-J-Duser.country=US"]
_ENV_STORE = "HAGBSM_STOREPASS"
_ENV_KEY = "HAGBSM_KEYPASS"

KEY_ALGORITHM = "RSA"
KEY_SIZE = 4096
SIGNATURE_ALGORITHM = "SHA256withRSA"
DEFAULT_VALIDITY_DAYS = 10_000   # ~27 years; Google Play requires validity beyond 2033


class SigningError(Exception):
    """kind: bad_password, bad_key_password, not_keystore, alias_not_found, no_private_key,
    exists, tool_missing, failed"""

    def __init__(self, kind: str, message: str, detail: str = ""):
        super().__init__(message)
        self.kind = kind
        self.detail = detail


@dataclass
class CertInfo:
    sha256: str            # colon-separated uppercase hex
    sha1: str
    subject: str
    issuer: str
    serial: str
    not_before: str        # ISO 8601 UTC
    not_after: str
    key_algorithm: str
    key_size: int
    signature_algorithm: str

    def to_dict(self) -> dict:
        return dict(self.__dict__)


@dataclass
class AliasEntry:
    alias: str
    entry_type: str        # PrivateKeyEntry, trustedCertEntry, SecretKeyEntry

    @property
    def has_private_key(self) -> bool:
        return self.entry_type == "PrivateKeyEntry"


def format_fingerprint(hexstr: str) -> str:
    h = re.sub(r"[^0-9A-Fa-f]", "", hexstr).upper()
    return ":".join(h[i:i + 2] for i in range(0, len(h), 2))


def normalize_fingerprint(fp: str) -> str:
    return re.sub(r"[^0-9A-F]", "", (fp or "").upper())


def cert_info(cert: x509.Certificate) -> CertInfo:
    der = cert.public_bytes(Encoding.DER)
    pub = cert.public_key()
    if isinstance(pub, rsa.RSAPublicKey):
        alg, size = "RSA", pub.key_size
    elif isinstance(pub, ec.EllipticCurvePublicKey):
        alg, size = f"EC ({pub.curve.name})", pub.curve.key_size
    elif isinstance(pub, dsa.DSAPublicKey):
        alg, size = "DSA", pub.key_size
    elif isinstance(pub, ed25519.Ed25519PublicKey):
        alg, size = "Ed25519", 256
    else:
        alg, size = type(pub).__name__, 0
    sig = cert.signature_hash_algorithm
    return CertInfo(
        sha256=format_fingerprint(hashlib.sha256(der).hexdigest()),
        sha1=format_fingerprint(hashlib.sha1(der).hexdigest()),
        subject=cert.subject.rfc4514_string(),
        issuer=cert.issuer.rfc4514_string(),
        serial=format(cert.serial_number, "X"),
        not_before=cert.not_valid_before_utc.isoformat(),
        not_after=cert.not_valid_after_utc.isoformat(),
        key_algorithm=alg,
        key_size=size,
        signature_algorithm=(sig.name.upper() if sig else "") + (" with " + alg.split(" ")[0] if sig else ""),
    )


def detect_store_type(path: Path) -> str:
    with open(path, "rb") as fh:
        head = fh.read(4)
    if head == b"\xfe\xed\xfe\xed":
        return "JKS"
    if head == b"\xce\xce\xce\xce":
        return "JCEKS"
    if head[:1] == b"\x30":
        return "PKCS12"
    return "unknown"


def escape_dn_value(value: str) -> str:
    """Escape an X.500 attribute value for keytool's -dname."""
    out = re.sub(r'([,+="\\<>;])', r"\\\1", value.strip())
    if out.startswith("#"):
        out = "\\" + out
    return out


def build_dname(common_name: str, organization: str = "", org_unit: str = "", locality: str = "",
                state: str = "", country: str = "") -> str:
    if not common_name.strip():
        raise ValueError("A common name (for example your publisher name) is required.")
    if country and not re.fullmatch(r"[A-Za-z]{2}", country.strip()):
        raise ValueError("The country must be a two-letter code such as US or GB.")
    parts = [("CN", common_name), ("OU", org_unit), ("O", organization), ("L", locality),
             ("ST", state), ("C", country.upper())]
    return ", ".join(f"{k}={escape_dn_value(v)}" for k, v in parts if v and v.strip())


def _classify_keytool_error(output: str) -> SigningError:
    low = output.lower()
    if "password was incorrect" in low or "keystore password was incorrect" in low:
        return SigningError("bad_password", "The keystore password is incorrect.", output)
    if "cannot recover key" in low or "given final block not properly padded" in low:
        return SigningError("bad_key_password", "The key password is incorrect.", output)
    if "unrecognized keystore format" in low or "invalid keystore format" in low or "not a keystore" in low:
        return SigningError("not_keystore", "The selected file is not a supported keystore.", output)
    if re.search(r"alias <.*> does not exist", low):
        return SigningError("alias_not_found", "That alias does not exist in the keystore.", output)
    if "already exists" in low:
        return SigningError("exists", "The keystore or alias already exists.", output)
    return SigningError("failed", "keytool reported an error.", output)


def _keytool(tools: AndroidTools, args, store_password: str, key_password: str = None, timeout=180):
    try:
        exe = tools.require_keytool()
    except ToolMissingError as exc:
        raise SigningError("tool_missing", str(exc)) from exc
    env = {_ENV_STORE: store_password}
    if key_password is not None:
        env[_ENV_KEY] = key_password
    try:
        res = run([exe, *_KT_LOCALE, *args], env_extra=env, timeout=timeout)
    except ToolMissingError as exc:
        raise SigningError("tool_missing", str(exc)) from exc
    if res.returncode != 0 or "keytool error" in res.output.lower():
        raise _classify_keytool_error(res.output)
    return res


def list_aliases(tools: AndroidTools, keystore: Path, store_password: str) -> list:
    res = _keytool(tools, ["-list", "-v", "-keystore", str(keystore), "-storepass:env", _ENV_STORE], store_password)
    entries, alias = [], None
    for line in res.stdout.splitlines():
        if line.startswith("Alias name: "):
            alias = line[len("Alias name: "):].strip()
        elif line.startswith("Entry type: ") and alias is not None:
            entries.append(AliasEntry(alias, line[len("Entry type: "):].strip()))
            alias = None
    return entries


def read_certificate(tools: AndroidTools, keystore: Path, store_password: str, alias: str) -> CertInfo:
    res = _keytool(tools, ["-exportcert", "-rfc", "-alias", alias, "-keystore", str(keystore),
                           "-storepass:env", _ENV_STORE], store_password)
    match = re.search(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", res.stdout, re.S)
    if not match:
        raise SigningError("failed", "keytool did not return a certificate.", res.output)
    return cert_info(x509.load_pem_x509_certificate(match.group(0).encode()))


def verify_key_access(tools: AndroidTools, keystore: Path, store_password: str, alias: str, key_password: str) -> None:
    """Prove the private key can be unlocked by asking keytool to sign a certificate request with it.
    The request is written to stdout and discarded."""
    _keytool(tools, ["-certreq", "-alias", alias, "-keystore", str(keystore),
                     "-storepass:env", _ENV_STORE, "-keypass:env", _ENV_KEY], store_password, key_password)


def generate_keystore(tools: AndroidTools, dest: Path, alias: str, password: str, dname: str,
                      validity_days: int = DEFAULT_VALIDITY_DAYS) -> CertInfo:
    """Create a new PKCS12 keystore at `dest` (which must not exist) and verify it.

    PKCS12 keystores use a single password for the store and the key; keytool enforces this.
    If anything fails after keytool created the file, the partial keystore is removed so it can
    never be mistaken for a valid identity.
    """
    dest = Path(dest)
    if dest.exists():
        raise SigningError("exists", f"{dest.name} already exists. Existing keystores are never overwritten.")
    if len(password) < 6:
        raise SigningError("failed", "Keystore passwords must be at least 6 characters.")
    dest.parent.mkdir(parents=True, exist_ok=True)
    created = False
    try:
        _keytool(tools, [
            "-genkeypair", "-keystore", str(dest), "-storetype", "PKCS12", "-alias", alias,
            "-keyalg", KEY_ALGORITHM, "-keysize", str(KEY_SIZE), "-sigalg", SIGNATURE_ALGORITHM,
            "-validity", str(int(validity_days)), "-dname", dname,
            "-storepass:env", _ENV_STORE, "-keypass:env", _ENV_KEY,
        ], password, password, timeout=300)
        created = dest.exists()
        if not created:
            raise SigningError("failed", "keytool finished but no keystore file was created.")
        verify_key_access(tools, dest, password, alias, password)
        return read_certificate(tools, dest, password, alias)
    except BaseException:
        if created or dest.exists():
            dest.unlink(missing_ok=True)
        raise


# --- APK inspection -------------------------------------------------------------

APK_VERIFIED = "verified"          # apksigner verified the signature
APK_CERT_ONLY = "cert_only"        # certificate read, signature not cryptographically verified
APK_INVALID = "invalid"            # signature does not verify / not a signed APK
APK_UNDETERMINED = "undetermined"
APK_TOOL_MISSING = "tool_missing"


@dataclass
class ApkInspection:
    status: str
    message: str
    signer_sha256: list = field(default_factory=list)   # formatted fingerprints
    schemes: dict = field(default_factory=dict)         # {"v1": True, ...}
    rotation_detected: bool = False
    detail: str = ""


def inspect_apk(tools: AndroidTools, apk: Path) -> ApkInspection:
    apk = Path(apk)
    if not apk.is_file():
        return ApkInspection(APK_UNDETERMINED, "The APK file was not found.")
    if not zipfile.is_zipfile(apk):
        return ApkInspection(APK_INVALID, "The file is not a valid APK (it is not a ZIP archive).")

    if tools.has_apksigner:
        res = run([tools.java, "-jar", tools.apksigner_jar, "verify", "--print-certs", "--verbose", str(apk)],
                  timeout=300)
        return _parse_apksigner(res.returncode, res.stdout, res.stderr)

    if tools.has_keytool:
        res = run([tools.keytool, *_KT_LOCALE, "-printcert", "-rfc", "-jarfile", str(apk)], timeout=120)
        pems = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", res.stdout, re.S)
        if pems:
            fps = []
            for pem in pems:
                fp = cert_info(x509.load_pem_x509_certificate(pem.encode())).sha256
                if fp not in fps:
                    fps.append(fp)
            return ApkInspection(
                APK_CERT_ONLY,
                "The signing certificate was read from the APK's v1 (JAR) signature, but the signature "
                "itself was not verified because apksigner is not available. Install Android SDK "
                "build-tools for full verification.",
                fps, {"v1": None})
        return ApkInspection(
            APK_TOOL_MISSING,
            "No v1 (JAR) signature certificate was found, and apksigner is not available to read newer "
            "signature schemes. Install Android SDK build-tools (apksigner) and try again.",
            detail=res.output)

    return ApkInspection(APK_TOOL_MISSING, "Neither apksigner nor keytool is available to inspect APK signatures.")


def _parse_apksigner(returncode: int, stdout: str, stderr: str) -> ApkInspection:
    text = stdout + "\n" + stderr
    schemes = {}
    for m in re.finditer(r"Verified using (v[\d.]+) scheme[^:]*:\s*(true|false)", text):
        schemes[m.group(1)] = m.group(2) == "true"
    fps = []
    for m in re.finditer(r"Signer (?:#\d+|\([^)]*\)) certificate SHA-256 digest:\s*([0-9a-fA-F]+)", text):
        fp = format_fingerprint(m.group(1))
        if fp not in fps:
            fps.append(fp)
    rotation = bool(re.search(r"Signer \(minSdkVersion|lineage", text, re.I)) or schemes.get("v3.1", False)
    if returncode != 0 or "DOES NOT VERIFY" in text:
        errors = [l.strip() for l in text.splitlines() if l.strip().startswith("ERROR")]
        msg = "The APK signature does not verify."
        if errors:
            msg += " " + errors[0]
        return ApkInspection(APK_INVALID, msg, fps, schemes, rotation, text.strip())
    if not fps:
        return ApkInspection(APK_UNDETERMINED, "apksigner did not report a signing certificate.",
                             schemes=schemes, detail=text.strip())
    return ApkInspection(APK_VERIFIED, "apksigner verified the APK signature.", fps, schemes, rotation, text.strip())


# --- comparison -----------------------------------------------------------------

CMP_MATCH = "match"
CMP_MATCH_UNVERIFIED = "match_unverified"
CMP_MISMATCH = "mismatch"
CMP_INVALID = "invalid"
CMP_UNDETERMINED = "undetermined"
CMP_TOOL_MISSING = "tool_missing"
CMP_NO_IDENTITY = "no_identity"

CMP_TITLES = {
    CMP_MATCH: "Certificate matches",
    CMP_MATCH_UNVERIFIED: "Certificate matches (signature not verified)",
    CMP_MISMATCH: "Certificate differs",
    CMP_INVALID: "APK signature invalid",
    CMP_UNDETERMINED: "Certificate cannot be determined",
    CMP_TOOL_MISSING: "Required tool unavailable",
    CMP_NO_IDENTITY: "No project signing identity to compare with",
}


@dataclass
class Comparison:
    result: str
    title: str
    notes: list


def compare_apk(inspection: ApkInspection, expected_sha256: str) -> Comparison:
    notes = [
        "A matching certificate is necessary for an update to install, but it is not the only "
        "requirement: the package name must also match and the new build's version code must be higher.",
        "If the app is distributed through Google Play with Play App Signing, users receive APKs signed "
        "by Google's app signing key, not by your upload key. Compare against the app signing "
        "certificate shown in Play Console for those installs.",
    ]
    if inspection.rotation_detected:
        notes.insert(0, "This APK uses signing-key rotation (APK Signature Scheme v3). Older certificates "
                        "in its lineage may also be accepted by Android for updates.")
    if len(inspection.signer_sha256) > 1:
        notes.insert(0, "The APK has more than one signer; all signers must match for updates.")

    status = inspection.status
    if status == APK_TOOL_MISSING:
        return Comparison(CMP_TOOL_MISSING, CMP_TITLES[CMP_TOOL_MISSING], [inspection.message])
    if status == APK_INVALID:
        return Comparison(CMP_INVALID, CMP_TITLES[CMP_INVALID], [inspection.message])
    if status == APK_UNDETERMINED or not inspection.signer_sha256:
        return Comparison(CMP_UNDETERMINED, CMP_TITLES[CMP_UNDETERMINED], [inspection.message])
    if not expected_sha256:
        return Comparison(CMP_NO_IDENTITY, CMP_TITLES[CMP_NO_IDENTITY],
                          ["Link or create an Android signing identity for this project to compare."])
    exp = normalize_fingerprint(expected_sha256)
    found = [normalize_fingerprint(f) for f in inspection.signer_sha256]
    if exp in found and all(f == exp for f in found):
        if status == APK_VERIFIED:
            return Comparison(CMP_MATCH, CMP_TITLES[CMP_MATCH], notes)
        return Comparison(CMP_MATCH_UNVERIFIED, CMP_TITLES[CMP_MATCH_UNVERIFIED], [inspection.message] + notes)
    return Comparison(CMP_MISMATCH, CMP_TITLES[CMP_MISMATCH],
                      ["The APK was signed with a different certificate than this project's identity. "
                       "Android will refuse to install it as an update over a build signed with the "
                       "project identity (and vice versa)."] + notes[1:])
